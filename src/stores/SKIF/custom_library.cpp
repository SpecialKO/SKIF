bool SKIF_RemoveCustomAppID (uint32_t appid)
{
  static SKIF_CommonPathsCache& _path_cache = SKIF_CommonPathsCache::GetInstance ( );

  std::wstring SKIFRegistryKey = SK_FormatStringW (LR"(SOFTWARE\Kaldaien\Special K\Games\%i\)", appid);
  std::wstring SKIFCustomPath  = SK_FormatStringW (LR"(%ws\Assets\Custom\%i\)", _path_cache.specialk_userdata, appid);
  SKIFCustomPath += L"\0\0";

  SHFILEOPSTRUCTW fileOps{};
  fileOps.wFunc = FO_DELETE;
  fileOps.pFrom = SKIFCustomPath.c_str();
  fileOps.fFlags = FOF_NO_UI;

  SHFileOperationW (&fileOps);
  RegDeleteKeyExW  (HKEY_CURRENT_USER, SKIFRegistryKey.c_str(), KEY_WOW64_64KEY, 0);

  return true;
}

int SKIF_AddCustomAppID (std::wstring name, std::wstring exePath, std::wstring args, std::wstring workingPath)
{
  /*
    name          - String -- Title/Name
    exe           - String -- Full Path to executable
    launchOptions - String -- Cmd line args
    id            - Autogenerated
    installDir    - Autogenerated
    workingDir    - String -- Optional, defaults to installDir
    exeFileName   - Autogenerated
  */

  DWORD   appId  = 1; // Assume 1 in case the registry fails

  HKEY    hKey;
  DWORD32 dwData = 0;
  DWORD   dwSize = sizeof (DWORD32);
  bool    failed = false;

  // We're expressively using .c_str() and not .wstring()
  //   because the latter adds a bunch of undesirable
  //     null terminators that screw the registry over.
  std::filesystem::path p  = std::filesystem::path (exePath);
  std::wstring exe         = p.lexically_normal(),
               exeFileName = p.filename().lexically_normal(),
               installDir  = p.parent_path().lexically_normal(),
               workingDir  = (! workingPath.empty())
                              ? workingPath
                              : installDir;

  // Strip null terminators
  //name.erase(std::find(name.begin(), name.end(), '\0'), name.end());
  //args.erase(std::find(args.begin(), args.end(), '\0'), args.end());

  if (RegCreateKeyExW (HKEY_CURRENT_USER, LR"(SOFTWARE\Kaldaien\Special K\Games\)", 0, NULL, REG_OPTION_NON_VOLATILE, KEY_READ | KEY_WRITE | KEY_WOW64_64KEY, NULL, &hKey, NULL) == ERROR_SUCCESS)
  {
    if (RegGetValueW (hKey, NULL, L"NextID", RRF_RT_REG_DWORD, NULL, &dwData, &dwSize) == ERROR_SUCCESS)
      appId = dwData;

    std::wstring wsAppID = LR"(SOFTWARE\Kaldaien\Special K\Games\)" + std::to_wstring(appId);

    HKEY    hSubKey;
    if (RegCreateKeyExW (HKEY_CURRENT_USER, wsAppID.c_str(), 0, NULL, REG_OPTION_NON_VOLATILE, KEY_READ | KEY_WRITE | KEY_WOW64_64KEY, NULL, &hSubKey, NULL) == ERROR_SUCCESS)
    {
      if (ERROR_SUCCESS != RegSetKeyValue (hSubKey, NULL, L"ID",            REG_DWORD, &appId, sizeof(DWORD)))
        failed = true;
      if (ERROR_SUCCESS != RegSetKeyValue (hSubKey, NULL, L"Name",          REG_SZ,    (LPBYTE) name       .data ( ), (DWORD) name       .size ( ) * sizeof(wchar_t)))
        failed = true;
      if (ERROR_SUCCESS != RegSetKeyValue (hSubKey, NULL, L"Exe",           REG_SZ,    (LPBYTE) exe        .data ( ), (DWORD) exe        .size ( ) * sizeof(wchar_t)))
        failed = true;
      if (ERROR_SUCCESS != RegSetKeyValue (hSubKey, NULL, L"ExeFileName",   REG_SZ,    (LPBYTE) exeFileName.data ( ), (DWORD) exeFileName.size ( ) * sizeof(wchar_t)))
        failed = true;
      if (ERROR_SUCCESS != RegSetKeyValue (hSubKey, NULL, L"InstallDir",    REG_SZ,    (LPBYTE) installDir .data ( ), (DWORD) installDir .size ( ) * sizeof(wchar_t)))
        failed = true;
      if (ERROR_SUCCESS != RegSetKeyValue (hSubKey, NULL, L"WorkingDir",    REG_SZ,    (LPBYTE) workingDir .data ( ), (DWORD) workingDir .size ( ) * sizeof(wchar_t)))
        failed = true;
      if (ERROR_SUCCESS != RegSetKeyValue (hSubKey, NULL, L"LaunchOptions", REG_SZ,    (LPBYTE) args       .data ( ), (DWORD) args       .size ( ) * sizeof(wchar_t)))
        failed = true;

      RegCloseKey (hSubKey);
    }

    if (! failed)
    {
      PLOG_INFO << "Custom game:";
      PLOG_INFO << "ID:            " << std::to_string(appId);
      PLOG_INFO << "Name:          " << name;
      PLOG_INFO << "Exe:           " << exe;
      PLOG_INFO << "ExeFileName:   " << exeFileName;
      PLOG_INFO << "InstallDir:    " << installDir;
      PLOG_INFO << "WorkingDir:    " << workingDir;
      PLOG_INFO << "LaunchOptions: " << args;
      PLOG_INFO << "Successfully added custom game to SKIF!";

      DWORD appIdNext = appId + 1;
      RegSetKeyValue(hKey, NULL, L"NextID", REG_DWORD, &appIdNext, sizeof(DWORD));
    }

    RegCloseKey (hKey);
  }

  if (failed)
    appId = 0;

  return appId;
}

bool SKIF_ModifyCustomAppID (app_record_s* pApp, std::wstring_view exePath, std::wstring_view args, std::wstring workingPath)
{
  /*
    exe           - String -- Full Path to executable
    launchOptions - String -- Cmd line args
    id            - Autogenerated
    installDir    - Autogenerated
    workingDir    - String -- Optional, defaults to installDir
    exeFileName   - Autogenerated
  */

  HKEY hKey;
  bool failed = false;

  // We're expressively using .c_str() and not .wstring()
  //   because the latter adds a bunch of undesirable
  //     null terminators that screw the registry over.
  std::filesystem::path p  = std::filesystem::path (exePath);
  std::wstring exe         = p.lexically_normal(),
               exeFileName = p.filename().lexically_normal(),
               installDir  = p.parent_path().lexically_normal(),
               workingDir  = (! workingPath.empty())
                              ? workingPath
                              : installDir;

  std::wstring key = SK_FormatStringW(LR"(SOFTWARE\Kaldaien\Special K\Games\%lu)", pApp->id);

  // Strip null terminators
  //args.erase(std::find(args.begin(), args.end(), '\0'), args.end());

  if (RegOpenKeyExW (HKEY_CURRENT_USER, key.c_str(), 0, KEY_READ | KEY_WRITE | KEY_WOW64_64KEY, &hKey) == ERROR_SUCCESS)
  {
    std::wstring wsAppID = std::to_wstring (pApp->id);

    if (ERROR_SUCCESS != RegSetKeyValue (hKey, NULL, L"Exe",           REG_SZ,    (LPBYTE) exe        .data ( ),
                                                                                   (DWORD) exe        .size ( ) * sizeof(wchar_t)))
      failed = true;
    if (ERROR_SUCCESS != RegSetKeyValue (hKey, NULL, L"ExeFileName",   REG_SZ,    (LPBYTE) exeFileName.data ( ),
                                                                                   (DWORD) exeFileName.size ( ) * sizeof(wchar_t)))
      failed = true;
    if (ERROR_SUCCESS != RegSetKeyValue (hKey, NULL, L"InstallDir",    REG_SZ,    (LPBYTE) installDir. data ( ),
                                                                                   (DWORD) installDir. size ( ) * sizeof(wchar_t)))
      failed = true;
    if (ERROR_SUCCESS != RegSetKeyValue (hKey, NULL, L"WorkingDir",    REG_SZ,    (LPBYTE) workingDir. data ( ),
                                                                                   (DWORD) workingDir. size ( ) * sizeof(wchar_t)))
      failed = true;
    if (ERROR_SUCCESS != RegSetKeyValue (hKey, NULL, L"LaunchOptions", REG_SZ,    (LPBYTE) args.       data ( ),
                                                                                   (DWORD) args.       size ( ) * sizeof(wchar_t)))
      failed = true;

    RegCloseKey (hKey);
  }

  if (failed == false)
  {
    pApp->install_dir                                         = installDir;
    pApp->launch_configs.begin()->second.executable           = exeFileName;
    pApp->launch_configs.begin()->second.executable_utf8      = SK_WideCharToUTF8(exeFileName);
    pApp->launch_configs.begin()->second.executable_path      = exe;
    pApp->launch_configs.begin()->second.executable_path_utf8 = SK_WideCharToUTF8(exe);
    pApp->launch_configs.begin()->second.install_dir          = pApp->install_dir;
    pApp->launch_configs.begin()->second.working_dir          = workingDir;
    pApp->launch_configs.begin()->second.working_dir_utf8     = SK_WideCharToUTF8(pApp->launch_configs.begin()->second.working_dir);
    pApp->launch_configs.begin()->second.launch_options       = args;
    pApp->launch_configs.begin()->second.description.clear();
    pApp->launch_configs.begin()->second.description_utf8.clear();
    pApp->specialk.profile_dir                                = exeFileName; // THIS CAN BE WRONG!!!!
    pApp->specialk.profile_dir_utf8                           = SK_WideCharToUTF8(pApp->specialk.profile_dir);
  }

  return ! failed;
}

void SKIF_GetCustomAppIDs (app_list_t* apps)
{
  PLOG_INFO << "Detecting custom SKIF games...";

  HKEY    hKey;
  DWORD   dwIndex  = 0,
          dwResult = 0,
          dwSize   = 0;
  DWORD32 dwData   = 0;
  WCHAR   szSubKey[MAX_PATH]     = { };
  WCHAR   szData  [MAX_PATH * 2] = { };

  extern uint32_t SelectNewSKIFGame;

  /* Load custom titles from registry */
  if (RegOpenKeyExW (HKEY_CURRENT_USER, LR"(SOFTWARE\Kaldaien\Special K\Games\)", 0, KEY_READ | KEY_WOW64_64KEY, &hKey) == ERROR_SUCCESS)
  {
    if (RegQueryInfoKeyW (hKey, NULL, NULL, NULL, &dwIndex, NULL, NULL, NULL, NULL, NULL, NULL, NULL) == ERROR_SUCCESS)
    {
      while (dwIndex > 0)
      {
        dwIndex--;

        dwSize   = sizeof (szSubKey) / sizeof (WCHAR);
        dwResult = RegEnumKeyExW (hKey, dwIndex, szSubKey, &dwSize, NULL, NULL, NULL, NULL);

        if (dwResult == ERROR_NO_MORE_ITEMS)
          break;

        if (dwResult == ERROR_SUCCESS)
        {
          HKEY hSubKey = nullptr;

          if (RegOpenKeyExW (HKEY_CURRENT_USER, SK_FormatStringW (LR"(SOFTWARE\Kaldaien\Special K\Games\%ws)", szSubKey).c_str(), 0, KEY_READ | KEY_WOW64_64KEY, &hSubKey) == ERROR_SUCCESS)
          {
            dwSize = sizeof (DWORD32);
            if (RegGetValueW (hSubKey, NULL, L"ID", RRF_RT_REG_DWORD, NULL, &dwData, &dwSize) == ERROR_SUCCESS)
            {
              app_record_custom_s record (dwData);

              record.id = dwData;
              record.store      = app_record_s::Store::Custom;
              record.store_utf8 = "Custom";
              record._status.installed = true;

              dwSize = sizeof(szData) / sizeof (WCHAR);
              if (RegGetValueW (hSubKey, NULL, L"Name", RRF_RT_REG_SZ, NULL, &szData, &dwSize) == ERROR_SUCCESS)
                record.names.normal = SK_WideCharToUTF8 (szData);
              record.names.original = record.names.normal;

              dwSize = sizeof (szData) / sizeof (WCHAR);
              if (RegGetValueW (hSubKey, NULL, L"InstallDir", RRF_RT_REG_SZ, NULL, &szData, &dwSize) == ERROR_SUCCESS)
                record.install_dir = szData;

              dwSize = sizeof (szData) / sizeof (WCHAR);
              if (RegGetValueW (hSubKey, NULL, L"ExeFileName", RRF_RT_REG_SZ, NULL, &szData, &dwSize) == ERROR_SUCCESS) // L"Exe"
              {
                app_record_s::launch_config_s lc;
                lc.id           = 0;
                lc.valid        = 1;
                lc.executable   = szData;
                lc.install_dir  = record.install_dir;
                lc.working_dir  = record.install_dir; // Default to install dir

                dwSize = sizeof (szData) / sizeof (WCHAR);
                if (RegGetValueW (hSubKey, NULL, L"WorkingDir", RRF_RT_REG_SZ, NULL, &szData, &dwSize) == ERROR_SUCCESS)
                  lc.working_dir = szData;

                dwSize = sizeof (szData) / sizeof (WCHAR);
                if (RegGetValueW (hSubKey, NULL, L"Exe", RRF_RT_REG_SZ, NULL, &szData, &dwSize) == ERROR_SUCCESS)
                  lc.executable_path = szData;

                dwSize = sizeof (szData) / sizeof (WCHAR);
                if (RegGetValueW (hSubKey, NULL, L"LaunchOptions", RRF_RT_REG_SZ, NULL, &szData, &dwSize) == ERROR_SUCCESS)
                  lc.launch_options = szData;

                record.launch_configs.emplace (0, lc);

                record.specialk.profile_dir              = lc.executable;
                record.specialk.profile_dir_utf8         = SK_WideCharToUTF8(record.specialk.profile_dir);
                record.specialk.injection.injection.type = InjectionType::Global;

                std::string entry_name = record.names.normal; // Copied first: the record is moved from below

                app_entry_t
                  pair (std::move (entry_name), std::make_unique <app_record_custom_s> (std::move (record)));

                apps->emplace_back (std::move (pair));
              }
            }

            RegCloseKey (hSubKey);
          }
        }
      }
    }

    RegCloseKey (hKey);
  }
}

bool
SKIF_Custom_AddGame (void)
{
  if (AddGamePopup == PopupState_Closed)
    return false;

  bool ret = false;

  static SKIF_RegistrySettings& _registry   = SKIF_RegistrySettings::GetInstance ( );

  // Always use same size
  float fAddGamePopupWidth = 560.0f * SKIF_ImGui_GlobalDPIScale;

  if (SKIF_ImGui_BeginPopup ("Add Game###AddGamePopup", nullptr, ImVec2 (fAddGamePopupWidth, 0.0f)))
  {
    /*
      name          - String -- Title/Name
      exe           - String -- Full Path to executable
      launchOptions - String -- Cmd line args
      id            - Autogenerated
      installDir    - Autogenerated
      exeFileName   - Autogenerated
    */

    if (AddGamePopup == PopupState_Open)
    {
      // Set the popup as opened after it has appeared (fixes popup not opening from other tabs)
      ImGuiWindow* window = ImGui::FindWindowByName ("###AddGamePopup");
      if (window != nullptr && ! window->Appearing)
        AddGamePopup = PopupState_Opened;
    }

    // ImGui's buf_size includes the null terminator, so passing MAX_PATH / 1024 to these slightly larger buffers is safe
    static char charName     [MAX_PATH + 2] = { },
                charPath     [MAX_PATH + 2] = { },
                charWorkDir  [MAX_PATH + 2] = { },
                charArgs     [    1024 + 2] = { };
    static bool error        = false,
                errorWorkDir = false;

    auto _ProcessFilePath = [&](LPCWSTR pwszPath) -> bool
    {
      bool __error = false;

      std::filesystem::path path           = pwszPath; // Wide-string std::filesystem::path
      std::filesystem::path pathDiscard    = pwszPath; // Wide-string std::filesystem::path which will be discarded
      std::string           pathFullPath   = SK_WideCharToUTF8  (pathDiscard.wstring());
      std::wstring          pathExtension  = SKIF_Util_ToLowerW (pathDiscard.extension().wstring());
      std::string           pathInstallDir = SK_WideCharToUTF8  (pathDiscard.parent_path().lexically_normal());
      std::string           pathFilename   = SK_WideCharToUTF8  (pathDiscard.replace_extension().filename().wstring()); // This removes the extension from pathDiscard

      if (pathExtension == L".lnk")
      {
        WCHAR wszTarget    [MAX_PATH + 2] = { };
        WCHAR wszWorkingDir[MAX_PATH + 2] = { };
        WCHAR wszArguments [MAX_PATH + 2] = { };

        SKIF_Util_ResolveShortcut (SKIF_ImGui_hWnd, path.c_str(), wszTarget, wszArguments, wszWorkingDir, MAX_PATH * sizeof (WCHAR));

        if (! PathFileExists (wszTarget))
        {
          __error = true;
          strncpy (charPath, "\0", MAX_PATH);
        }

        else {
          std::wstring productName = SKIF_Util_GetProductName (wszTarget);

          strncpy (charPath,    SK_WideCharToUTF8 (wszTarget).c_str(),                  MAX_PATH);
          strncpy (charWorkDir, SK_WideCharToUTF8 (wszWorkingDir).c_str(),              MAX_PATH);
          strncpy (charArgs,    SK_WideCharToUTF8 (wszArguments).c_str(),               1024);
          strncpy (charName, (productName != L"")
                              ? SK_WideCharToUTF8 (productName).c_str()
                              : pathFilename.c_str(), MAX_PATH);
        }
      }

      else if (pathExtension == L".exe") {
        std::wstring productName = SKIF_Util_GetProductName (path.c_str());

        strncpy (charPath,    pathFullPath.c_str(),   MAX_PATH);
        strncpy (charWorkDir, pathInstallDir.c_str(), MAX_PATH);
        strncpy (charName, (productName != L"")
                            ? SK_WideCharToUTF8 (productName).c_str()
                            : pathFilename.c_str(),   MAX_PATH);
      }

      else if (pathExtension == L".bat") {
        strncpy (charPath,    pathFullPath.c_str(),   MAX_PATH);
        strncpy (charWorkDir, pathInstallDir.c_str(), MAX_PATH);
      }

      else {
        __error = true;
        strncpy (charPath,    "\0", MAX_PATH);
        strncpy (charWorkDir, "\0", MAX_PATH);
      }

      return __error;
    };

    // Process drag-n-dropped executables / shortcuts
    extern std::wstring dragDroppedFilePathGame;
    if (! dragDroppedFilePathGame.empty())
    {
      error = _ProcessFilePath (dragDroppedFilePathGame.c_str());
      dragDroppedFilePathGame.clear();
    }

    ImGui::TreePush    ("AddGameTreePush");

    SKIF_ImGui_Spacing ( );

    ImVec2 vButtonSize = ImVec2(80.0f * SKIF_ImGui_GlobalDPIScale, 0.0f);

    float fBtnX = ImGui::GetCursorPosX ( );

    // Path / Executable
    if (ImGui::Button  ("Browse...###BrowsePath", vButtonSize))
    {
      LPWSTR pwszFilePath = NULL;
      HRESULT hr          =
        SKIF_Util_FileExplorer_BrowseForFile (&pwszFilePath, SKIF_ImGui_hWnd, { { L"Executables", L"*.exe;*.bat" } }, FOS_NODEREFERENCELINKS | FOS_NOVALIDATE | FOS_FILEMUSTEXIST);

      if (hr == HRESULT_FROM_WIN32(ERROR_CANCELLED))
      {
        // If cancelled, do nothing
      }

      else if (SUCCEEDED(hr))
      {
        error = _ProcessFilePath (pwszFilePath);
      }

      else {
        error = true;
        strncpy (charPath,    "\0", MAX_PATH);
        strncpy (charWorkDir, "\0", MAX_PATH);
      }
    }

    SKIF_ImGui_BlockDragMoveWhenItemActive ( );

    ImGui::SameLine    ( );

    float fAddGamePopupX = ImGui::GetCursorPosX ( );

    ImGui::PushStyleColor (ImGuiCol_Text, ImGui::GetStyleColorVec4(ImGuiCol_TextDisabled));
    ImGui::InputText   ("###GamePath", charPath, MAX_PATH, ImGuiInputTextFlags_ReadOnly);
    SKIF_ImGui_BlockDragMoveWhenItemActive ( );
    ImGui::PopStyleColor ( );
    ImGui::SameLine    ( );
    ImGui::Text        ("Path");

    if (error)
    {
      ImGui::SetCursorPosX (fAddGamePopupX);
      ImGui::TextColored (ImGui::GetStyleColorVec4(ImGuiCol_SKIF_Warning), "Incompatible type! Please select another file.");
    }

    ImGui::SetCursorPosX (fBtnX);

    // Working Directory
    if (ImGui::Button  ("Change...###BrowseWorkDir", vButtonSize))
    {
      errorWorkDir = false;
      LPWSTR pwszWorkingDir = NULL;

      HRESULT hr          =
        SKIF_Util_FileExplorer_BrowseForFolder (&pwszWorkingDir, SKIF_ImGui_hWnd);

      if (hr == HRESULT_FROM_WIN32(ERROR_CANCELLED))
      {
        // If cancelled, do nothing
      }

      else if (SUCCEEDED(hr))
      {
        std::string           pathWorkDir = SK_WideCharToUTF8(pwszWorkingDir);
        strncpy (charWorkDir, pathWorkDir.c_str(), MAX_PATH);
      }

      else {
        errorWorkDir = true;
        strncpy (charWorkDir, "\0", MAX_PATH);
      }
    }

    SKIF_ImGui_BlockDragMoveWhenItemActive ( );

    ImGui::SameLine    ( );

    ImGui::PushStyleColor (ImGuiCol_Text, ImGui::GetStyleColorVec4(ImGuiCol_TextDisabled));
    ImGui::InputText   ("###GameWorkDir", charWorkDir, MAX_PATH, ImGuiInputTextFlags_ReadOnly);
    SKIF_ImGui_BlockDragMoveWhenItemActive ( );
    ImGui::PopStyleColor ( );
    ImGui::SameLine    ( );
    ImGui::Text        ("Working Directory");

    if (errorWorkDir)
    {
      ImGui::SetCursorPosX (fAddGamePopupX);
      ImGui::TextColored (ImGui::GetStyleColorVec4(ImGuiCol_SKIF_Warning), "Incompatible folder! Please select another folder.");
    } else {
      // Empty line
      ImGui::NewLine   ( );
    }

    ImGui::SetCursorPosX (fAddGamePopupX);

    // Name
    ImGui::InputText   ("###GameName", charName, MAX_PATH);
    SKIF_ImGui_BlockDragMoveWhenItemActive ( );
    ImGui::SameLine    ( );
    ImGui::Text        ("Name");

    ImGui::SetCursorPosX (fAddGamePopupX);

    ImGui::InputTextEx ("###GameArgs", "Leave empty if unsure", charArgs, 1024, ImVec2(0,0), ImGuiInputTextFlags_None);
    SKIF_ImGui_BlockDragMoveWhenItemActive ( );
    ImGui::SameLine    ( );
    ImGui::Text        ("Launch Options");

    SKIF_ImGui_Spacing ( );
    SKIF_ImGui_Spacing ( );

    ImGui::SetCursorPosX (fAddGamePopupWidth / 2 - vButtonSize.x - 20.0f * SKIF_ImGui_GlobalDPIScale);

    bool disabled = false;

    if ((charName   [0] == '\0' || std::isspace(charName   [0])) ||
        (charPath   [0] == '\0' || std::isspace(charPath   [0])) ||
        (charWorkDir[0] == '\0' || std::isspace(charWorkDir[0])))
      disabled = true;

    if (disabled)
    {
      SKIF_ImGui_PushDisableState ( );
    }

    if (ImGui::Button  ("Add Game", vButtonSize))
    {
      int newAppId = SKIF_AddCustomAppID (SK_UTF8ToWideChar(charName), SK_UTF8ToWideChar(charPath), SK_UTF8ToWideChar(charArgs), SK_UTF8ToWideChar(charWorkDir));

      if (newAppId > 0)
      {
        // Attempt to extract the icon from the given executable straight away
        //std::wstring SKIFCustomPath = SK_FormatStringW (LR"(%ws\Assets\Custom\%i\icon-original.png)", _path_cache.specialk_userdata, newAppId);
        //SKIF_Util_SaveExtractExeIcon (SK_UTF8ToWideChar(charPath), SKIFCustomPath);

        _registry.uiLastSelectedGame  = newAppId;
        _registry.uiLastSelectedStore = (int)app_record_s::Store::Custom;
        _registry.regKVLastSelectedGame .putData (_registry.uiLastSelectedGame);
        _registry.regKVLastSelectedStore.putData (_registry.uiLastSelectedStore);
        RepopulateGames = true; // Rely on the RepopulateGames method instead
      }

      // Clear variables
      error               = false;
      errorWorkDir        = false;
      strncpy (charName,    "\0", MAX_PATH);
      strncpy (charPath,    "\0", MAX_PATH);
      strncpy (charWorkDir, "\0", MAX_PATH);
      strncpy (charArgs,    "\0", 1024);

      // Used to indicate that the cover should be unloaded.
      ret = true;

      AddGamePopup = PopupState_Closed;
    }

    SKIF_ImGui_BlockDragMoveWhenItemActive ( );

    if (disabled)
    {
      SKIF_ImGui_PopDisableState  ( );
    }

    ImGui::SameLine    ( );

    ImGui::SetCursorPosX (fAddGamePopupWidth / 2 + 20.0f * SKIF_ImGui_GlobalDPIScale);

    if (ImGui::Button  ("Cancel", vButtonSize))
    {
      // Clear variables
      error               = false;
      errorWorkDir        = false;
      strncpy (charName,    "\0", MAX_PATH);
      strncpy (charPath,    "\0", MAX_PATH);
      strncpy (charWorkDir, "\0", MAX_PATH);
      strncpy (charArgs,    "\0", 1024);

      AddGamePopup = PopupState_Closed;
    }

    SKIF_ImGui_BlockDragMoveWhenItemActive ( );

    SKIF_ImGui_Spacing ( );

    ImGui::TreePop     ( );
  }

  else {
   AddGamePopup = PopupState_Closed;
  }

  SKIF_ImGui_EndPopup ( );

  return ret;
}

bool
SKIF_Custom_RemoveGame (uint32_t appid)
{
  if (RemoveGamePopup == PopupState_Closed)
    return false;

  if (appid == 0)
    return false;

  bool ret      = false;
  bool dontCare =  true;
  switch (SKIF_ImGui_ConfirmPrompt ("Remove Game?###RemoveGamePopup", &dontCare, "Are you sure you want to remove the game from the library?", "No changes will be made to the game files."))
  {
    case DChoice_Yes:
      if (SKIF_RemoveCustomAppID (appid))
        ret = true;

    case DChoice_No:
    case DChoice_Cancel:
      RemoveGamePopup = PopupState_Closed;
      break;
  }

  return ret;
}

